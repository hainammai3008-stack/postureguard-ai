-- Store a student's response when an audio posture warning was incorrect.
-- This table stores metadata only. It has no webcam image or video column.

create table if not exists public.incorrect_alert_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  session_id uuid not null references public.monitor_sessions(id) on delete cascade,
  posture text not null
    check (posture in ('leaning_left','leaning_right','leaning_backward','leaning_forward')),
  alerted_at timestamptz not null,
  reported_at timestamptz not null default now(),
  unique (user_id, session_id, alerted_at)
);

create index if not exists incorrect_alert_feedback_user_reported_idx
  on public.incorrect_alert_feedback(user_id, reported_at desc);

alter table public.incorrect_alert_feedback enable row level security;
